// Aeruvo service worker — app-shell caching + Firebase Cloud Messaging.
//
// ARCHITECTURE:
//   Firebase compat scripts are imported from /vendor/ (same-origin, static,
//   bundled at build time by scripts/generate-sw-config.cjs). This eliminates
//   any runtime CDN dependency during SW installation, ensuring the SW always
//   installs promptly regardless of network conditions.
//
//   /vendor/firebase-app-compat.js and /vendor/firebase-messaging-compat.js
//   are downloaded from the official Firebase CDN at build time (pinned to the
//   exact version in use) and served as same-origin static files. They are
//   gitignored and regenerated on every build.
//
//   /firebase-sw-config.js is generated by scripts/generate-sw-config.cjs from
//   VITE_FIREBASE_* env vars. It sets self.AERUVO_FIREBASE_CONFIG.

// ── Same-origin SW config (safe to importScripts at top level) ───────────
// This file is generated from same-origin env vars — no CDN, no latency.
try {
  importScripts("/firebase-sw-config.js");
} catch (e) {
  console.warn("[aeruvo:sw] firebase-sw-config.js unavailable:", e && e.message);
  self.AERUVO_FIREBASE_CONFIG = null;
}

// ── Same-origin Firebase vendor scripts (safe to importScripts at top level) ─
// Served from /vendor/ — same origin, downloaded at build time, no CDN latency.
// If missing (local dev without running prebuild), FCM is skipped gracefully.
if (self.AERUVO_FIREBASE_CONFIG) {
  try {
    importScripts("/vendor/firebase-app-compat.js");
    importScripts("/vendor/firebase-messaging-compat.js");
    firebase.initializeApp(self.AERUVO_FIREBASE_CONFIG);
    const messaging = firebase.messaging();

    // DATA-ONLY payload contract (Stage E Cloud Function must follow this):
    // Send data-only messages — no `notification` field. This handler reads
    // payload.data.title/body/url and calls showNotification() manually.
    // A `notification` field causes the browser to auto-display AND this
    // handler fires → two notifications. Stage E must use data-only messages.
    messaging.onBackgroundMessage((payload) => {
      const title = (payload.data && payload.data.title) || "Aeruvo";
      const body  = (payload.data && payload.data.body)  || "Check today's forecast.";
      const url   = (payload.data && payload.data.url)   || "/";
      self.registration.showNotification(title, {
        body,
        icon:  "/icon-192.png",
        badge: "/icon-96.png",
        tag:   "aeruvo-rain-reminder",
        data:  { url },
      });
    });

    console.log("[aeruvo:sw] FCM initialized");
  } catch (e) {
    // FCM init failure must never block install/activate/fetch.
    console.warn("[aeruvo:sw] FCM init failed:", e && e.message);
  }
}

// ── App-shell cache ───────────────────────────────────────────────────────

const CACHE_NAME = "aeruvo-shell-v3";
const STATIC_EXTENSIONS = [
  ".js", ".css", ".woff2", ".woff", ".png", ".svg", ".ico", ".webmanifest",
];

self.addEventListener("install", (event) => {
  console.log("[aeruvo:sw] install");
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  console.log("[aeruvo:sw] activate");
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys.filter((k) => k !== CACHE_NAME).map((k) => caches.delete(k)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

function isStaticAsset(url) {
  return STATIC_EXTENSIONS.some((ext) => url.pathname.endsWith(ext));
}

self.addEventListener("fetch", (event) => {
  const { request } = event;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  if (isStaticAsset(url)) {
    event.respondWith(
      caches.open(CACHE_NAME).then(async (cache) => {
        const cached = await cache.match(request);
        const network = fetch(request)
          .then((res) => {
            if (res.ok) cache.put(request, res.clone());
            return res;
          })
          .catch(() => cached);
        return cached || network;
      }),
    );
    return;
  }

  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request)
        .then((res) => {
          caches
            .open(CACHE_NAME)
            .then((cache) => cache.put(request, res.clone()));
          return res;
        })
        .catch(() =>
          caches
            .match(request)
            .then((cached) => cached || caches.match("/")),
        ),
    );
  }
});

// ── Notification click ────────────────────────────────────────────────────

self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const url =
    (event.notification.data && event.notification.data.url) || "/";
  event.waitUntil(
    self.clients
      .matchAll({ type: "window", includeUncontrolled: true })
      .then((clients) => {
        const existing = clients.find(
          (c) => new URL(c.url).origin === self.location.origin,
        );
        if (existing) return existing.focus();
        return self.clients.openWindow(url);
      }),
  );
});
